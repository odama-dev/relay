export type IconName = keyof typeof icons;

type IconProps = {
  name: IconName;
  size?: number;
  className?: string;
  "aria-label"?: string;
};

/** Every icon renders at the app's single weight (--icon-stroke, globals.css). */
export function Icon({ name, size = 16, className, ...rest }: IconProps) {
  const Cmp = icons[name];
  return (
    <Cmp
      width={size}
      height={size}
      className={cn("shrink-0", className)}
      color="currentColor"
      {...rest}
    />
  );
}
